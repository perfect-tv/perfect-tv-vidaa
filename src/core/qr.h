/* QR-код версии 5-L (37×37 модулей, до 106 байт ASCII в байтовом режиме, маска 0) — без сторонних библиотек и сетевых
 * сервисов: адрес ТВ и одноразовый ключ не уходят из домашней сети. Тот же кодировщик, что у веб-версии. */
#ifndef PTV_QR_H
#define PTV_QR_H
#include <stdint.h>

#define QR_SIZE 37
/* m[y][x] = 1 — тёмный модуль. 0 — готово; -1 — текст длиннее 106 байт или не ASCII. */
int qr_encode(const char *text, uint8_t m[QR_SIZE][QR_SIZE]);
#endif
