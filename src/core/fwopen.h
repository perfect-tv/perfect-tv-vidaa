/* Входящий доступ к порту телефонной страницы через файрвол ТВ.
 * Прошивки VIDAA режут входящие TCP на порты выше 1023 (цепочки FIREWALL_IN_EULAON*): сервер слушает, но телефон
 * в той же сети не достучится, и QR не работает. На время показа QR открываем ровно одно правило: TCP на этот порт
 * и этот адрес ТВ, только из подсети его интерфейса. Правило помечено комментарием, снимается в fw_close() и, на
 * случай падения приложения, независимым сторожем (sh, setsid) через LIFETIME+60 с. Ошибка не мешает работе: QR
 * всё равно показывается (в журнал — fw_open_failed <причина>). Тот же приём, что у VPN в VidaApp Store. */
#ifndef PTV_FWOPEN_H
#define PTV_FWOPEN_H
/* 0 — правило поставлено и проверено (-C); -1 — нет (причина в журнале). guard_seconds — срок сторожа. */
int fw_open(const char *ip, int port, int guard_seconds);
void fw_close(void);
#endif
