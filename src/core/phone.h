/* Ввод с телефона: одноразовая страница в домашней сети (как у Android- и веб-версии). Телевизор показывает QR-код
 * адреса http://<адрес ТВ>:47381/<ключ>; телефон открывает форму (адрес плейлиста, название, адрес программы) и
 * отправляет её сюда. Сервер — неблокирующий, опрашивается из главного потока (phone_poll в tick окна), без потоков.
 * Ключ — 16 случайных шестнадцатеричных знаков; без него страница отвечает 404. Через 10 минут или после приёма —
 * остановка. Ключ и адрес в журнал не пишутся. */
#ifndef PTV_PHONE_H
#define PTV_PHONE_H
#include <stddef.h>

typedef struct { char url[2048], name[160], epg[2048]; } phone_result;

/* Запустить (или перезапустить с новым ключом); url — адрес для QR. 0 — слушаем; -1 — нет сети (err). */
int phone_start(char *url, size_t cap, char *err, size_t errn);
void phone_stop(void);
int phone_running(void);
/* Обработать соединения. 1 — пришёл ответ (r заполнен, сервер остановлен). */
int phone_poll(phone_result *r);
/* Адрес ТВ в локальной сети (IPv4): 0 — найден. */
int phone_lan_ip(char *out, size_t cap);
#endif
